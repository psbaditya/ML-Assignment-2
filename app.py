"""Interactive evaluation of five saved classifiers on uploaded labeled test data."""
from pathlib import Path
import json
import joblib
import pandas as pd
import streamlit as st
from sklearn.metrics import (accuracy_score, roc_auc_score, precision_score,
                             recall_score, f1_score, matthews_corrcoef,
                             confusion_matrix, classification_report)

ROOT = Path(__file__).resolve().parent
st.set_page_config(page_title='Model Evaluation Lab', layout='wide')
st.title('Classification Model Comparison')
st.caption('Compare five pre-trained models on an uploaded, labeled CSV — no retraining on test data.')

manifest_path = ROOT / 'model_manifest.json'
if not manifest_path.exists():
    st.error('Missing model files. Run train_models.py in the BITS Virtual Lab first.')
    st.stop()
manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
model_names = list(manifest['models'])
feature_columns = manifest['features']
choice = st.selectbox('Choose classifier', model_names)
upload = st.file_uploader('Upload test data CSV (with target column)', type=['csv'])
if upload is None:
    st.info('Upload test_data.csv generated by train_models.py to view the results.')
    st.stop()

try:
    data = pd.read_csv(upload)
except Exception as e:
    st.error(f'Unable to read the CSV: {e}')
    st.stop()
required = feature_columns + ['target']
missing = [name for name in required if name not in data.columns]
if missing:
    st.error(f'Missing columns: {missing}')
    st.stop()
if data.empty:
    st.error('The uploaded CSV is empty.')
    st.stop()
try:
    features = data[feature_columns].apply(pd.to_numeric, errors='raise')
    targets = pd.to_numeric(data['target'], errors='raise').astype(int)
    if features.isna().any().any() or targets.isna().any():
        raise ValueError('Missing values were found.')
    if not set(targets.unique()).issubset({0, 1}):
        raise ValueError('Target values must be 0 or 1.')
except Exception as e:
    st.error(f'Invalid test data: {e}')
    st.stop()

@st.cache_resource
def load_model(name: str):
    path = ROOT / 'model' / manifest['models'][name]
    return joblib.load(path)

def evaluate(name: str):
    clf = load_model(name)
    predictions = clf.predict(features)
    scores = clf.predict_proba(features)[:, 1]
    return {
        'Accuracy': accuracy_score(targets, predictions),
        'AUC': roc_auc_score(targets, scores) if targets.nunique() == 2 else float('nan'),
        'Precision': precision_score(targets, predictions, zero_division=0),
        'Recall': recall_score(targets, predictions, zero_division=0),
        'F1': f1_score(targets, predictions, zero_division=0),
        'MCC': matthews_corrcoef(targets, predictions),
    }, predictions

try:
    metrics, predictions = evaluate(choice)
    st.subheader(f'Results: {choice}')
    cols = st.columns(3)
    for idx, (key, value) in enumerate(metrics.items()):
        cols[idx % 3].metric(key, f'{value:.4f}')
    st.subheader('Confusion matrix')
    matrix = confusion_matrix(targets, predictions, labels=[0, 1])
    st.dataframe(pd.DataFrame(matrix, index=['Actual 0', 'Actual 1'],
                              columns=['Predicted 0', 'Predicted 1']))
    st.subheader('Classification report')
    st.text(classification_report(targets, predictions, zero_division=0))
    st.subheader('Compare all five models')
    comparison = []
    for name in model_names:
        result, _ = evaluate(name)
        comparison.append({'Model': name, **result})
    st.dataframe(pd.DataFrame(comparison).round(4), hide_index=True)
except Exception as exc:
    st.error(f'Could not evaluate the model: {exc}')
